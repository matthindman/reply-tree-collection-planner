"""Bin the two reference populations into the planner's (size, root-replies) grid.

usage: python3 export_tables.py REPO JAPAN_SIM_NPZ OUT_JS
Reads the same inputs as ../collection_strategy_2026_11_19/cost_model.py. Output: a JS file defining
REF_TABLES = {japan2011: {...}, usArchives: {...}}, each a sparse list of cells
[sizeBin, rootBin, conversations per reply, mean size].
"""
import json, sys
from pathlib import Path
import numpy as np

REPO, SIM, OUT = Path(sys.argv[1]), sys.argv[2], sys.argv[3]

def edges():
    e = list(range(1, 21)); dec = 10
    while dec < 1e7:
        e += [int(round(x * dec)) for x in (2.5, 3, 4, 5, 6, 7.5, 10, 12.5, 15, 20)]
        dec *= 10
    return np.array(e)

E = edges()
def binof(v):
    return np.searchsorted(E, v, side="right") - 1

def table(S, K, w):
    tot = float((w * (S - 1)).sum()); w = w / tot
    i, k = binof(S), binof(np.maximum(K, 1))
    nb = len(E); key = i * nb + k
    W = np.bincount(key, weights=w, minlength=nb * nb)
    WS = np.bincount(key, weights=w * S, minlength=nb * nb)
    nz = np.flatnonzero(W)
    cells = [[int(c // nb), int(c % nb), float(f"{W[c]:.6g}"), float(f"{WS[c] / W[c]:.6g}")] for c in nz]
    summ = dict(conversations_per_M=1e6 * float(w.sum()),
                share100=float((w * (S - 1))[S >= 100].sum()), share1000=float((w * (S - 1))[S >= 1000].sum()),
                trees100_per_M=1e6 * float(w[S >= 100].sum()),
                rootdriven100=float(w[(S >= 100) & (K >= (S - 1) / 2)].sum() / w[S >= 100].sum()))
    return dict(cells=cells, summary=summ)

def us():
    S, K, W = [], [], []
    for a in ("news", "midterms"):
        pt = np.load(REPO / f"claude/general_model/data/{a}_pertree.npz")
        px = np.load(REPO / f"joint/main/results/{a}_prefix_sizes.npz")
        ok = px["paper_eligible"].astype(bool) & (px["size30"] >= 2)
        s30 = px["size30"][ok]; k = np.minimum(pt["root_degree"][ok], s30 - 1)
        S.append(s30); K.append(k); W.append(np.full(ok.sum(), 0.5 / (s30 - 1).sum()))
    return np.concatenate(S).astype(np.int64), np.concatenate(K).astype(np.int64), np.concatenate(W)

def japan():
    z = np.load(SIM); sm = z["small_joint"]; si, ki = np.nonzero(sm)
    S = np.r_[si, z["size"]]; K = np.r_[ki, z["root_degree"]]
    w = np.r_[sm[si, ki], np.ones(len(z["size"]))].astype(float)
    keep = S >= 2
    return S[keep].astype(np.int64), K[keep].astype(np.int64), w[keep]

out = {"edges": E.tolist(), "japan2011": table(*japan()), "usArchives": table(*us())}
for k in ("japan2011", "usArchives"):
    print(k, len(out[k]["cells"]), "cells", out[k]["summary"])
Path(OUT).write_text("// Generated by data/export_tables.py. Do not edit by hand.\nconst REF_TABLES = " + json.dumps(out, separators=(",", ":")) + ";\nif (typeof module !== 'undefined') module.exports = REF_TABLES;\n")
print("bytes", Path(OUT).stat().st_size)
