/* Build src/scenario_tables.js from data/scenarios.json.

   usage: node data/make_scenarios.js
   Each entry of scenarios.json is one of:
     { params }                      a full 18-parameter set
     { base, knobs }                 another entry's parameters with the planner's model controls moved
     { base, knobs, solve }          the same, with one control solved so that the share of replies in
                                     conversations of 100+ posts hits solve.share100
     { skip: true }                  kept as a record only
   Every scenario is simulated with a fixed seed and stored as a binned population. */
const fs = require('fs'), path = require('path');
const G = require('../src/sim.js');
const NB = G.NB, E = G.EDGES;
const NEUTRAL = { pop: 1, lam: 1, dC0: 0, dMu: 0, sigScale: 1, dBranch: 0 };
// must match modelParams() in src/app.js
function applyKnobs(base, knobs) {
  const k = Object.assign({}, NEUTRAL, knobs), p = Object.assign({}, base);
  p.w = 1 - Math.min(0.95, Math.max(0.001, (1 - p.w) * k.pop));
  p.t1 /= k.lam; p.a1 /= k.lam; p.t2 /= k.lam; p.a2 /= k.lam;
  p.mu += k.dMu; p.sig *= k.sigScale; p.c0 += k.dC0; p.f0 += k.dBranch; p.g0 += k.dBranch;
  return p;
}
function summarise(r) {
  const { w, ws } = G.normalise(r.W, r.WS), cells = []; const o = { share100: 0, share1000: 0, conv100: 0, quiet: 0 };
  for (let i = 0; i < NB; i++) for (let j = 0; j < NB; j++) {
    const c = i * NB + j; if (!w[c]) continue; const m = ws[c] / w[c];
    cells.push([i, j, +w[c].toPrecision(6), +m.toPrecision(6)]);
    const kmid = j < 20 ? E[j] : Math.sqrt(E[j] * ((j + 1 < NB ? E[j + 1] : 2 * E[j]) - 1));
    if (E[i] >= 100) { o.share100 += ws[c] - w[c]; o.conv100 += w[c]; if (kmid < (m - 1) / 2) o.quiet += w[c]; }
    if (E[i] >= 1000) o.share1000 += ws[c] - w[c];
  }
  return { cells, share100: o.share100, share1000: o.share1000, conv100: 1e6 * o.conv100, driven: 1 - o.quiet / o.conv100 };
}
const sim = (p, rounds) => G.simulate(p, { seed: 20261119, rounds, budget: 3e6 });
const file = path.join(__dirname, 'scenarios.json'), sc = JSON.parse(fs.readFileSync(file, 'utf8')), out = {};
const paramsOf = (name) => sc[name].params || applyKnobs(paramsOf(sc[name].base), sc[name].knobs);
for (const name in sc) {
  const s = sc[name]; if (s.skip) continue;
  if (s.solve) {                         // bisection on one control, in logs, then rounded to two significant figures
    const key = s.solve.knob; let lo = Math.log(s.solve.range[0]), hi = Math.log(s.solve.range[1]);
    const f = (x) => summarise(sim(applyKnobs(paramsOf(s.base), Object.assign({}, s.knobs, { [key]: Math.exp(x) })), 5)).share100;
    const up = f(hi) > f(lo);
    for (let it = 0; it < 9; it++) { const mid = (lo + hi) / 2, v = f(mid); if ((v < s.solve.share100) === up) lo = mid; else hi = mid; }
    s.knobs = Object.assign({}, s.knobs, { [key]: +Math.exp((lo + hi) / 2).toPrecision(2) });
  }
  const t0 = Date.now(), p = paramsOf(name), r = sim(p, 30), sum = summarise(r);
  out[name] = { label: s.label, base: s.params ? name : s.base, knobs: Object.assign({}, NEUTRAL, s.params ? {} : s.knobs), params: s.params || undefined, source: s.source,
                trees: r.trees, excess: r.excess, cells: sum.cells };
  console.log(name.padEnd(8), JSON.stringify(s.params ? 'full parameter set' : s.knobs), ((Date.now() - t0) / 1000).toFixed(0) + 's', r.trees, 'conversations', '| share100', (100 * sum.share100).toFixed(2) + '%', 'share1000', (100 * sum.share1000).toFixed(2) + '%', 'conv100/M', sum.conv100.toFixed(0), 'root-driven', (100 * sum.driven).toFixed(0) + '%');
}
fs.writeFileSync(file, JSON.stringify(sc, null, 1));
fs.writeFileSync(path.join(__dirname, '..', 'src', 'scenario_tables.js'), '// Generated by data/make_scenarios.js. Do not edit by hand.\nconst SCENARIO_TABLES = ' + JSON.stringify(out) + ';\nif (typeof module !== \'undefined\') module.exports = SCENARIO_TABLES;\n');
